export type ProofPackKind = ResultKind | "Revision"

export type ProofPackResult = {
  participantRef: string
  kind: ProofPackKind
  claim: string
  proof: string
  partnerName: string | null
}

export type ProofPackVersion = {
  version: number
  madeOn: string
  by: string | null
  periodStart: string
  periodEnd: string
  change: { title: string; detail: string }
  months: string[]
  results: ProofPackResult[]
}

type MonthCounts = Partial<Record<ProofPackKind, [fromPartners: number, ownDelivery: number]>>

const partners = ["Riverside Trust", "Brightwell Training", "Harbour Skills"]

function monthResults(claim: string, first: number, counts: MonthCounts) {
  const results: ProofPackResult[] = []
  let next = first

  for (const [kind, [fromPartners, ownDelivery]] of Object.entries(counts) as [ProofPackKind, [number, number]][]) {
    for (let index = 0; index < fromPartners + ownDelivery; index++) {
      results.push({
        participantRef: `NS-${String(next++).padStart(4, "0")}`,
        kind,
        claim,
        proof: kind === "Revision" ? "Change to a closed claim" : "All checks passed",
        partnerName: index < fromPartners ? partners[results.length % partners.length] : null,
      })
    }
  }

  return results
}

const months = {
  june: monthResults("June 2027", 1001, { Enrolled: [7, 2], Onboarded: [15, 3], Outcome: [9, 2] }),
  july: monthResults("July 2027", 2001, { Enrolled: [8, 2], Onboarded: [17, 4], Outcome: [12, 3], Revision: [1, 0] }),
  august: monthResults("August 2027", 3001, { Enrolled: [9, 2], Onboarded: [18, 4], Outcome: [14, 3], Revision: [2, 0] }),
  september: monthResults("September 2027", 4001, { Enrolled: [9, 4], Onboarded: [19, 4], Outcome: [14, 3] }),
}

function version(
  number: number,
  madeOn: string,
  periodEnd: string,
  change: ProofPackVersion["change"],
  covered: (keyof typeof months)[],
): ProofPackVersion {
  return {
    version: number,
    madeOn,
    by: null,
    periodStart: "2027-06-01",
    periodEnd,
    change,
    months: covered.map((month) => months[month][0].claim),
    results: covered.flatMap((month) => months[month]),
  }
}

