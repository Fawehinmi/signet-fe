export type ProofPackJob = {
  version: number
  by: string
  startedAt: number
  finishedAt: number | null
  failed: boolean
}

const generationTime = 20_000
const shownFor = 30 * 60_000
const jobsByProgramme: Record<string, ProofPackJob | undefined> = {}

function versionsFor(programmeId: string) {
  versionsByProgramme[programmeId] ??= []
  return versionsByProgramme[programmeId]
}

function buildVersion(programmeId: string, job: ProofPackJob): ProofPackVersion {
  const previous = versionsFor(programmeId).at(-1)

  return {
    version: job.version,
    madeOn: today(),
    by: job.by,
    periodStart: previous?.periodStart ?? today(),
    periodEnd: previous?.periodEnd ?? today(),
    change: {
      title: previous ? `Same results as Version ${previous.version}` : "First version",
      detail: `Generated by ${job.by}`,
    },
    months: previous?.months ?? [],
    results: previous?.results ?? [],
  }
}

function settle(programmeId: string) {
  const job = jobsByProgramme[programmeId]
  if (!job || job.finishedAt || Date.now() - job.startedAt < generationTime) return

  try {
    versionsFor(programmeId).push(buildVersion(programmeId, job))
  } catch {
    job.failed = true
  }
  job.finishedAt = Date.now()
}

export async function getProofPackVersions(programmeId: string) {
  settle(programmeId)
  return [...versionsFor(programmeId)].reverse()
}

export async function getProofPackVersion(programmeId: string, number: number) {
  settle(programmeId)
  return versionsFor(programmeId).find((item) => item.version === number) ?? null
}

export async function getProofPackProgress(programmeId: string): Promise<ProofPackProgress | null> {
  settle(programmeId)
  const job = jobsByProgramme[programmeId]
  if (!job) return null

  if (!job.finishedAt) {
    const percent = Math.min(99, Math.round(((Date.now() - job.startedAt) / generationTime) * 100))
    return { version: job.version, status: "generating", percent, step: percent < 35 ? 0 : 1 }
  }

  if (Date.now() - job.finishedAt > shownFor) return null
  return job.failed
    ? { version: job.version, status: "failed", percent: 0, step: 1 }
    : { version: job.version, status: "ready", percent: 100, step: 2 }
}

export async function startProofPack(programmeId: string, by: string) {
  settle(programmeId)
  const current = jobsByProgramme[programmeId]
  if (current && !current.finishedAt) return null

  const job: ProofPackJob = {
    version: (versionsFor(programmeId).at(-1)?.version ?? 0) + 1,
    by,
    startedAt: Date.now(),
    finishedAt: null,
    failed: false,
  }
  jobsByProgramme[programmeId] = job

  return job
}
